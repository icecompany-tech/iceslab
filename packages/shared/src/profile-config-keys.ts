import type { ProtocolName } from './transport.js';

/**
 * A-285: every top-level key of a profile's config, by who looks after it.
 *
 * The profile form builds the config afresh from its own fields on every save,
 * and the server's PUT replaces the stored config whole. So a key the form has
 * no field for is erased by the next save, unless the server carries it over
 * from what is stored, or the push sets it and it is never stored at all. On
 * 27.10 every key was one of the three; this list says which, and two tests
 * hold it to that: the backend's (the union is exactly the keys of the
 * protocol's config schema) and the frontend's (the form's save builds exactly
 * the `form` keys). A key added to a schema with no field, no carry-over and
 * no push then fails a test, not a profile on its next save.
 *
 *  - `form`: the profile form has a field for it and sends it (some only for
 *    the security or the network that uses them);
 *  - `keptByServer`: no field; an edit without it keeps the stored value
 *    (profiles.service.ts, updateProfile);
 *  - `setByPush`: never stored on the profile; the push sets it for each node.
 */
export interface ProfileConfigKeys {
  form: readonly string[];
  keptByServer: readonly { key: string; why: string }[];
  setByPush: readonly { key: string; why: string }[];
}

