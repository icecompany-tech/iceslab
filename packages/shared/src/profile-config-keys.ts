/** Every key the profile config of `protocol` may hold. */
export function profileConfigKeys(protocol: ProtocolName): string[] {
  const k = PROFILE_CONFIG_KEYS[protocol];
  return [...k.form, ...k.keptByServer.map((x) => x.key), ...k.setByPush.map((x) => x.key)];
}
