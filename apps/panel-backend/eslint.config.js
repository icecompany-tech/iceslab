import js from '@eslint/js'
import globals from 'globals'
import tseslint from 'typescript-eslint'
import { defineConfig, globalIgnores } from 'eslint/config'

// Линт бэкенда. Появился позже фронтового и намеренно уже: здесь нет правила
// про границы модулей, потому что такого правила у бэкенда и нет. Модули читают
// сервисы друг друга (подписка спрашивает каскады, очередь спрашивает и то и
// другое), и записать это запретом значило бы описать не то устройство, которое
// есть.
//
// Что он ловит: `any` и мёртвые объявления. Оба стоят дорого именно тут. `any`
// в бэкенде это обычно граница с чужими данными (jsonb, тело запроса, ответ
// ноды), и она либо разобрана и названа типом, либо не разобрана, и тогда об
// этом лучше знать. Мёртвое объявление это почти всегда остаток вырезанной
// ветки.
//
// ⚠ ГЕНЕРАТ НЕ ЛИНТУЕТСЯ. `src/generated/prisma` пишет генератор, править его
// нельзя, а весит он больше остального кода вместе взятого.
export default defineConfig([
  globalIgnores(['dist', 'src/generated']),
  {
    files: ['**/*.ts'],
    extends: [js.configs.recommended, tseslint.configs.recommended],
    languageOptions: { globals: globals.node },
  },
  {
    // Тесты читают сырые тела ответов и лезут в приватные поля адаптеров,
    // поэтому пустая функция-заглушка и `any` в разобранном JSON тут норма, а
    // не долг. Всё остальное к ним применяется как ко всему.
    files: ['**/*.test.ts', 'tests/**/*.ts'],
    rules: { '@typescript-eslint/no-empty-function': 'off' },
  },
])
