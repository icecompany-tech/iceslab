import { plural } from '@/lib/i18n'

type Vars = Record<string, unknown>

const ruCount = (one: string, few: string, many: string) => (vars: Vars = {}) => {
  const n = Number(vars.count ?? 0)
  return plural('ru', n, { one, few, many }).replaceAll('{count}', String(n)).replaceAll('{names}', String(vars.names ?? ''))
}
const enCount = (one: string, many: string) => (vars: Vars = {}) => {
  const n = Number(vars.count ?? 0)
  return plural('en', n, { one, many }).replaceAll('{count}', String(n)).replaceAll('{names}', String(vars.names ?? ''))
}

