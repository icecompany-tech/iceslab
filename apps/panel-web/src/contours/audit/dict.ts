const ruPlural = (n: number, one: string, few: string, many: string) => {
  const tens = n % 100
  const ones = n % 10
  if (tens >= 11 && tens <= 14) return many
  if (ones === 1) return one
  return ones >= 2 && ones <= 4 ? few : many
}

