import type { Node } from '@/lib/domain/nodes';

/**
 * Отказ ядра принять конфиг, приведённый к тому, что читает человек.
 *
 * Отказ ЕСТЬ только тогда, когда его прислали. Ни `lastInboundSyncAt`, ни
 * статус ноды его не заменяют: старый стамп это «пуш ещё в пути», и принять
 * одно за другое значит нарисовать красную строку там, где ничего не сломано.
 *
 * Состояние снимается само. Удачный пуш стирает поле на сервере, поэтому
 * «исправлено» рисовать нечем, и рисовать его не надо: зелёная строка на
 * каждой здоровой ноде выдавливает с экрана настоящую.
 */
export interface SyncRefusal {
  /** Когда пуш отвергли, ISO, как прислал сервер. */
  at: string;
  /** Причина словами ядра: одна строка, ради которой сюда смотрят. */
  reason: string;
  /** Весь ответ целиком, с префиксом агента и баннером ядра. */
  full: string;
}

export function refusalOf(node: Pick<Node, 'lastInboundSyncError'>): SyncRefusal | null {
  const e = node.lastInboundSyncError;
  if (!e || typeof e.message !== 'string' || e.message.trim() === '') return null;
  return { at: e.at, reason: coreReason(e.message), full: e.message };
}

/**
 * Хвост после последнего «>» это причина, как её сформулировало само ядро:
 * всё левее это цепочка подсистем, через которые ошибка поднималась, и она
 * одинаковая у половины отказов.
 *
 * Режем ТОЛЬКО на показе. Хранимое остаётся целым: это чужой вывод, и
 * урезать его в базе значит однажды лишить оператора того куска, ради
 * которого он и открыл карточку.
 */
export function coreReason(message: string): string {
  const flat = message.replace(/\s+/g, ' ').trim();
  const cut = flat.lastIndexOf('>');
  // Ядро ответило без цепочки: показываем то, что сказано, целиком, а не
  // пустую строку от «хвоста, которого нет».
  if (cut === -1) return flat;
  const tail = flat.slice(cut + 1).trim();
  return tail === '' ? flat : tail;
}
