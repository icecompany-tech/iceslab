import { describe, expect, it } from 'vitest';
import { DEFAULT_LINK_CONGESTION, LINK_CONGESTIONS } from '@iceslab/shared';

/**
 * Словарь управления перегрузкой во фронте ровно один, и он в контракте.
 *
 * Копий было ЧЕТЫРЕ, и жили они в двух разных слоях: нога каскада
 * (`lib/domain/cascades.ts`) и пользовательский tuic-инбаунд (тип значений
 * формы, дефолты формы, список литералом прямо в разметке `TuicSection`). Слои
 * разные, движок один, и значение, которого sing-box не знает, роняет конфиг
 * при разборе одинаково в обоих.
 *
 * Тест сторожит не состав списка, а сам факт копии: СОСТАВ перечисления
 * TypeScript не проверяет по построению, поэтому пятая копия появится молча и
 * молча же разойдётся с контрактом. Приём тот же, которым бэкенд сторожит
 * зеркало контракта у агента: читаем исходники и смотрим, не написан ли
 * словарь снова.
 *
 * Исходники берутся через `import.meta.glob`, а не через `node:fs`: у этого
 * приложения в типах нет `node`, и тащить его сюда ради одного теста значит
 * открыть его всем экранам.
 *
 * Проверки «список у формы профиля и у ноги каскада один» живут в своих
 * контурах: `lib` о контурах не знает, и это держит линт.
 */

const FILES = import.meta.glob('/src/**/*.{ts,tsx}', {
  query: '?raw',
  import: 'default',
  eager: true,
}) as Record<string, string>;

const SELF = '/src/lib/domain/linkCongestion.test.ts';

describe('словарь перегрузки', () => {
  it('1. во фронте нет ни одной своей копии списка', () => {
    // Ищем имя В КАВЫЧКАХ: так оно попадает в союз, массив или пропс, то есть
    // становится копией. Упоминание в комментарии через обратные кавычки это
    // объяснение, а не словарь, и запрещать его незачем.
    const guilty = Object.entries(FILES)
      .filter(([path]) => path !== SELF)
      .filter(([, code]) => /['"]new_reno['"]/.test(code))
      .map(([path]) => path);
    expect(guilty).toEqual([]);
  });

  it('2. глоб действительно читает исходники, а не пустоту', () => {
    // Без этого первый тест зеленеет сам по себе, если глоб перестанет
    // находить файлы: пустой список копий и пустой список файлов выглядят
    // одинаково.
    expect(Object.keys(FILES).length).toBeGreaterThan(100);
    expect(FILES['/src/lib/domain/cascades.ts']).toContain('LINK_CONGESTIONS');
  });

  it('3. контракт отдаёт непустой список, и дефолт стоит в нём', () => {
    expect(LINK_CONGESTIONS.length).toBeGreaterThan(0);
    expect(LINK_CONGESTIONS).toContain(DEFAULT_LINK_CONGESTION);
  });
});
