import { useSyncExternalStore } from 'react';

/**
 * Текущее время как ВНЕШНИЙ источник, а не как вызов посреди рендера.
 *
 * `Date.now()` прямо в разметке выдаёт при каждом вызове своё число, то есть
 * делает рендер нечистым: два рендера подряд с теми же пропсами рисуют разное,
 * и React вправе считать это ошибкой. Здесь время читается там, где React сам
 * его спрашивает, и меняется по своему тику.
 *
 * Снимок округляется до шага: иначе каждое чтение отличалось бы от предыдущего
 * на миллисекунды, React считал бы состояние изменившимся и перерисовывал бы
 * компонент без конца.
 *
 * Шаг задаёт и точность, и цену. Для обратного отсчёта в минутах 30 секунд это
 * ровно то, что нужно: цифра не врёт дольше половины своей единицы, а
 * перерисовок два в минуту.
 */
export function useNow(stepMs = 30_000): number {
  return useSyncExternalStore(
    (onChange) => {
      const id = setInterval(onChange, stepMs);
      return () => clearInterval(id);
    },
    () => Math.floor(Date.now() / stepMs) * stepMs,
    // На сервере времени нет и быть не должно: ноль здесь никогда не попадает
    // на экран, потому что панель рендерится только в браузере.
    () => 0,
  );
}
