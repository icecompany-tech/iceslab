import type { NodeCore } from '@/lib/domain/nodes';

/**
 * Достанет ли политика уровня ноды до этой машины.
 *
 * Применять правила это работа ЯДРА, а не ноды: сегодня из девяти адаптеров
 * агента `ApplyPolicy` реализует ровно один. На ноде с AmneziaWG, sing-box,
 * нативной hysteria, naive, mieru или mtproto правило «заблокировать»
 * выглядит применённым и не применяется, а панель об этом молчала.
 *
 * ТРИ состояния, и третье не округление второго:
 *
 *   applies         хотя бы одно ядро сказало, что рисует политику.
 *   not-applicable  ядра ответили, и ни одно её не рисует.
 *   unknown         спросить было некого либо никто не ответил.
 *
 * Считается ТОЛЬКО по `cores[].rendersPolicy`. Не по `Node.protocol`: это
 * ярлык «что поставили основным», а не список умений, и чтение его как
 * ограничения уже дважды стоило отказов рабочим парам.
 */
export type PolicyApplicability = 'applies' | 'not-applicable' | 'unknown';

export function policyApplicability(
  cores: NodeCore[] | null | undefined,
): PolicyApplicability {
  // `cores` пустой это НЕ «ядер нет»: агент ни разу не отчитался. На этой
  // разнице уже горели, весь полевой флот показывал degraded вечно. Пустой
  // список сюда же: нода, которая отчиталась и не назвала ни одного ядра, не
  // даёт оснований утверждать что-либо про политику.
  if (!cores || cores.length === 0) return 'unknown';

  if (cores.some((c) => c.rendersPolicy === true)) return 'applies';

  // «Не применима» требует, чтобы ответили ВСЕ и все ответили нет.
  //
  // Отсутствие поля означает «агент старше поля», и это не `false`. Пока хоть
  // одно ядро молчит, оно может оказаться тем самым, которое политику рисует,
  // и сказать «не применима» значило бы отказать по неполному списку. Частичный
  // ответ годится, чтобы сказать «да», и не годится, чтобы сказать «нет»: на
  // этом же правиле стоят ворота движков, и оно писано после двух инцидентов.
  if (cores.every((c) => c.rendersPolicy === false)) return 'not-applicable';

  return 'unknown';
}
